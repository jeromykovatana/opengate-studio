STUDIO_ROOT = HERE.parents[1]
WORKSPACE_ROOT = STUDIO_ROOT.parent

FW_DIR = Path(os.environ.get("SONY_FW_DIR", str(WORKSPACE_ROOT / "firmwares/a7siii/ghidra_targets")))
DESIGNS_DIR = Path(os.environ.get("STUDIO_DESIGNS_DIR", str(STUDIO_ROOT / "designs")))
UPSTREAM_DESIGNS_DIR = DESIGNS_DIR

BASE = 0x108000
LABEL = "s3read_v9"
CP_LO, CP_HI = 0xC0000, 0x2100000
AVCAM_PHYS, AVCAM_RESERVE = 0x401000000, "@0x401000000"
ID_FILES = {
    "/libmpr.so": "libmpr.so",
    "/libsencore.so": "libsencore.so",
    "/libJiritsu.so": "libJiritsu.so",
}
ID_PAGES = (0x128000, 0x4A8000, 0x86D000, 0xB11000)
DUMP_RANGES = (
    ("shadow", 0x1019000, 2),
    ("matrix", 0xF2E000, 3),
    ("sizetable", 0x13EC000, 1),
    ("records", 0x1FE0000, 4),
    ("kprint", 0xE0000, 32),
    ("bootlog", 0xC0000, 8),
    ("context", 0x11A3000, 4),
    ("resizework", 0x11B5000, 1),
    ("resizestate", 0x13FF000, 4),
    ("wbuf", 0x119A000, 2),
    ("display", 0x1E4000, 1),
    ("frametab", 0xD4D000, 1),
    ("paneltype", 0x14B9000, 1),
)
DESC, UNIT, CLIP, COMB = 0x38393C + 0xA02C, 0x38389C + 0xA02C, 0x38BBDC, 0x2D32B8 + 0x1150
NDESC, PROFILES = 689, ((0x39BCCC + 0xA02C, 373), (0x3B32CC + 0xA02C, 316))


def scan_rate30_longgop(av: bytes, existing_av: set[int]) -> tuple[list[tuple[int, bytes, bytes]], list[tuple[int, bytes]]]:
    """Build av-cam 29.97p (rate code 2) Long-GOP descriptors/profiles and key guards."""
    prof_off: dict[int, int] = {}
    for pbase, pcnt in PROFILES:
        for i in range(pcnt):
            prof_off[struct.unpack_from("<I", av, pbase + i * 0x100 + 0x20)[0]] = pbase + i * 0x100
    fams = ((0xE, {(0, 1), (1, 1)}), (4, {(0, 0), (1, 1)}))
    new_sites: list[tuple[int, bytes, bytes]] = []
    new_guards: list[tuple[int, bytes]] = []
    seen_prof: set[int] = set()
    w, h0, h1 = 3840, 2160, 2560
    old_h, new_h = struct.pack("<H", h0), struct.pack("<H", h1)
    old_hi, new_hi = struct.pack("<I", h0), struct.pack("<I", h1)
    for codec, groups in fams:
        for k in range(NDESC):
            o = DESC + k * 0x90
            codecid, infr, codfr, _f0c, _cls, chroma, bitl = struct.unpack_from("<7I", av, o)
            if codecid != codec or infr != 0 or codfr != 2 or (chroma, bitl) not in groups:
                continue
            if struct.unpack_from("<HH", av, o + 0x7E) != (w, h0):
                continue
            key = struct.unpack_from("<I", av, o + 0x28)[0]
            assert (o + 0x80) not in existing_av and av[o + 0x80:o + 0x82] == old_h
            new_sites.append((o + 0x80, old_h, new_h))
            new_guards.append((o + 0x28, av[o + 0x28:o + 0x2C]))
            if key in seen_prof:
                continue
            seen_prof.add(key)
            po = prof_off[key]
            assert struct.unpack_from("<HH", av, po + 4) == (w, h0) and struct.unpack_from("<II", av, po + 0x34) == (w, h0)
            assert struct.unpack_from("<H", av, po + 0x56)[0] == 0
            new_sites.append((po + 6, old_h, new_h))
            new_sites.append((po + 0x38, old_hi, new_hi))
            if struct.unpack_from("<HH", av, po + 0x8A) == (w, h0):
                new_sites.append((po + 0x8C, old_h, new_h))
    assert len(new_sites) == 48, f"Expected 48 rate-2 Long-GOP sites, got {len(new_sites)}"
    return new_sites, new_guards


def emit_multi_rec_sites(cp: bytes, design_name: str, header_name: str, rec_size: int = 0x15C) -> tuple[str, int, int, list[str]]:
    d = json.loads((DESIGNS_DIR / f"{design_name}.json").read_text(encoding="utf8"))
    assert d["artifact_sha256"] == hashlib.sha256(cp).hexdigest() and d["record_size"] == rec_size
    sites = sorted((int(p["addr"], 16), bytes.fromhex(p["old"]), bytes.fromhex(p["new"])) for p in d["patches"])
    assert len(sites) == 40
    cp_end = BASE + len(cp)
    out = [
        f"/* Generated by src/a7s3_501/gen_s3_packs.py from designs/{design_name}.json (a7S III 5.01). Do not edit. */",
        f"/* {len(sites)} sites, {sum(len(o) for _, o, _ in sites)} bytes, MULTI_REC ({', '.join(d['mode_ids'])}). */",
    ]
    rows = []
    for k, (a, old, new) in enumerate(sites):
        assert len(old) == len(new) and old != new and cp[a - BASE:a - BASE + len(old)] == old
        lo, hi = a & ~63, (a + len(old) + 63) & ~63
        assert hi - lo <= 4096 and 0xB11000 <= lo and hi <= cp_end
        out.append(f"static const u8 site{k}_old[{len(old)}] = {{ {hx(old)} }};")
        out.append(f"static const u8 site{k}_new[{len(new)}] = {{ {hx(new)} }};")
        rows.append(f"    {{ 0x{a:x}, {len(old)}, site{k}_old, site{k}_new, 0, 0 }},")
    assert all(a + len(o) <= b for (a, o, _), (b, _, _) in zip(sites, sites[1:])), "sites overlap"

    modes = sorted(int(m, 16) for m in d["stored_records"])
    assert [hex(m) for m in modes] == d["mode_ids"]
    offs: list[int] | None = None
    stock_m: list[list[bytes]] = []
    new_m: list[list[bytes]] = []
    for m in modes:
        sr = d["stored_records"][hex(m)]
        o = [int(x, 16) for x in sr["offsets_that_differ"]]
        assert offs is None or o == offs
        offs = o
        st_v, nw_v = [], []
        for v in ("ntsc", "pal"):
            s, n = bytes.fromhex(sr[v]["stock"]), bytes.fromhex(sr[v]["design"])
            assert len(s) == len(n) == rec_size and s[6] == s[7] == 1 and n[6:8] == bytes((16, 19))
            assert all(s[i] == n[i] for i in range(rec_size) if i not in o)
            st_v.append(bytes(s[i] for i in o))
            nw_v.append(bytes(n[i] for i in o))
        assert len(set(st_v + nw_v)) == 4, f"Mode {m:#x} variants not all distinct"
        stock_m.append(st_v)
        new_m.append(nw_v)
    assert offs is not None and offs[:2] == [6, 7] and 2 < len(offs) <= 128
    arr = lambda tbl: "{ " + ", ".join("{ " + ", ".join(f"{{ {hx(v)} }}" for v in row) + " }" for row in tbl) + " }"
    out += [
        "#define MULTI_REC 1",
        f"#define N_RECS {len(modes)}",
        "#define REC_VARIANTS 2",
        '#define REC_VARIANTS_TEXT "NTSC 60 Hz or PAL 50 Hz"',
        f"#define REC_BYTES {len(offs)}",
        'static const u32 rec_modes[N_RECS] = { ' + ", ".join(f"0x{m:x}" for m in modes) + " };",
        'static const char *const rec_mode_text[N_RECS] = { ' + ", ".join(f'"{m:#x}"' for m in modes) + " };",
        'static const char *const rec_variant_name[REC_VARIANTS] = { "NTSC (60 Hz)", "PAL (50 Hz)" };',
        f"static const unsigned short rec_offs[REC_BYTES] = {{ {', '.join(f'0x{k:x}' for k in offs)} }};",
        f"static const u8 rec_stock[N_RECS][REC_VARIANTS][REC_BYTES] = {arr(stock_m)};",
        f"static const u8 rec_new[N_RECS][REC_VARIANTS][REC_BYTES] = {arr(new_m)};",
        f'#define SITES_TEXT "{len(sites)}"',
        f'#define ALL_TEXT "{len(sites) + len(modes)}"',
        "struct cp_site { u64 address; u32 length; const u8 *stock; const u8 *changed; const unsigned short *offs; u32 noffs; };",
        "static const struct cp_site cp_sites[] = {",
        *rows,
        "};",
    ]
    write_utf8_lf(HERE / header_name, "\n".join(out) + "\n")
    return header_name, len(sites), len(offs), [hex(m) for m in modes]


def hx(b: bytes) -> str:
    return ", ".join(f"0x{x:02x}" for x in b)


def c_bytes(b: bytes) -> str:
    return "{" + ",".join(str(x) for x in b) + "}"


def h16(b: bytes) -> str:
    return hx(b.ljust(16, b"\x00"))


def check_libmpr_pt_load0(lm: bytes, entries: list[tuple[int, int, bytes, bytes]]) -> None:
    phoff = struct.unpack_from("<Q", lm, 0x20)[0]
    phentsize, phnum = struct.unpack_from("<HH", lm, 0x36)
    load0 = next(
        struct.unpack_from("<IIQQQQQQ", lm, phoff + k * phentsize)
        for k in range(phnum)
        if struct.unpack_from("<I", lm, phoff + k * phentsize)[0] == 1
    )
    assert load0[2] == 0 and load0[3] == 0
    max_end = max(a + len(o) for a, _, o, _ in entries)
    assert max_end <= load0[5], f"libmpr.so entry 0x{max_end:x} exceeds PT_LOAD[0] filesz 0x{load0[5]:x}"


def load_mp_pack_v19(av: bytes, lm: bytes, include_mp4: bool = True) -> dict:
    v1 = json.loads((UPSTREAM_DESIGNS_DIR / "ogfile2560_hs_s_s3_v1.json").read_text(encoding="utf8"))
    mp4 = json.loads((DESIGNS_DIR / "mp4_3x2_s3_501.json").read_text(encoding="utf8"))
    assert v1["artifact_sha256"] == {"libmpr.so": hashlib.sha256(lm).hexdigest(), "av-cam.bin": hashlib.sha256(av).hexdigest()}
    assert mp4["artifact_sha256"]["libmpr.so"] == hashlib.sha256(lm).hexdigest()
    assert not any(p["code"] for p in v1["patches"])

    sites: dict[str, list[tuple[int, bytes, bytes]]] = {"av-cam.bin": [], "libmpr.so": []}
    for p in v1["patches"]:
        off, old, new = int(p["file_off"], 16), bytes.fromhex(p["old"]), bytes.fromhex(p["new"])
        src = av if p["binary"] == "av-cam.bin" else lm
        assert len(old) == len(new) <= 16 and old != new and src[off:off + len(old)] == old
        sites[p["binary"]].append((off, old, new))

    existing_av = {off for off, _, _ in sites["av-cam.bin"]}
    r30_sites, r30_guards = scan_rate30_longgop(av, existing_av)
    sites["av-cam.bin"].extend(r30_sites)

    if include_mp4:
        v1_lm_offs = {off for off, _, _ in sites["libmpr.so"]}
        for p in mp4["patches"]:
            assert p["binary"] == "libmpr.so"
            off, old, new = int(p["file_off"], 16), bytes.fromhex(p["old"]), bytes.fromhex(p["new"])
            assert off not in v1_lm_offs
            assert len(old) == len(new) <= 16 and old != new and lm[off:off + len(old)] == old
            sites["libmpr.so"].append((off, old, new))
        assert len(sites["libmpr.so"]) == 12
    else:
        assert len(sites["libmpr.so"]) == 4

    assert len(sites["av-cam.bin"]) == 149

    g_av: list[tuple[int, bytes]] = [
        (UNIT + 0x20, av[UNIT + 0x20:UNIT + 0x30]),
        (CLIP + 0x50, av[CLIP + 0x50:CLIP + 0x60]),
    ]
    assert struct.unpack("<4I", g_av[0][1]) == (0x486, 0x474, 0x477, 0x47A)
    assert struct.unpack("<4I", g_av[1][1]) == (1, 3840, 2160, 23)
    for x in v1["descriptors"]:
        o = DESC + x["descriptor"] * 0x90 + 0x28
        assert struct.unpack_from("<I", av, o)[0] == x["profile_key"]
        g_av.append((o, av[o:o + 4]))
    g_av.extend(r30_guards)

    g_lm: list[tuple[int, bytes]] = []
    seen_lm_guards: set[int] = set()
    if include_mp4:
        for g in mp4["guards"]:
            assert g["binary"] == "libmpr.so"
            off, bs = int(g["file_off"], 16), bytes.fromhex(g["bytes"])
            assert 0 < len(bs) <= 16 and lm[off:off + len(bs)] == bs
            if off not in seen_lm_guards:
                g_lm.append((off, bs))
                seen_lm_guards.add(off)
    else:
        g_lm.append((0, lm[:16]))
        seen_lm_guards.add(0)
    for p in v1["patches"]:
        if p["binary"] == "libmpr.so":
            off = int(p["file_off"], 16)
            assert (off - 6 - COMB) % 0x18 == 0 and struct.unpack_from("<H", lm, off - 2)[0] == 3840
            g_off = off - 6
            if g_off not in seen_lm_guards:
                g_lm.append((g_off, lm[g_off:off]))
                seen_lm_guards.add(g_off)

    return {
        "name": "ogfile2560_hs_s_s3_v3" if include_mp4 else "ogfile2560_hs_s_s3_nometa",
        "header": "expected_mp_ogfile2560_hs_s_s3_v3.h" if include_mp4 else "expected_mp_ogfile2560_hs_s_s3_nometa.h",
        "sites": sites,
        "guards": {"av-cam.bin": g_av, "libmpr.so": g_lm},
        "comment": (
            "Union of 23.98p/25p/29.97p Long-GOP (4 L1-comb + 149 av-cam) and mp4_3x2_s3_501 (8 libmpr)."
            if include_mp4
            else "Data-only 23.98p/25p/29.97p Long-GOP fallback (4 L1-comb + 149 av-cam)."
        ),
    }


def load_mp_pack_b19(av: bytes, lm: bytes) -> dict:
    hb = json.loads((DESIGNS_DIR / "og_highbitrate_s3_501.json").read_text(encoding="utf8"))
    assert hb["artifact_sha256"]["av-cam.bin"] == hashlib.sha256(av).hexdigest()
    sites: dict[str, list[tuple[int, bytes, bytes]]] = {"av-cam.bin": [], "libmpr.so": []}
    for p in hb["patches"]:
        assert p["binary"] == "av-cam.bin"
        off, old, new = int(p["file_off"], 16), bytes.fromhex(p["old"]), bytes.fromhex(p["new"])
        assert len(old) == len(new) <= 16 and old != new and av[off:off + len(old)] == old
        sites["av-cam.bin"].append((off, old, new))
    assert len(sites["av-cam.bin"]) == 108

    g_av: list[tuple[int, bytes]] = []
    for g in hb["guards"]:
        assert g["binary"] == "av-cam.bin"
        off, bs = int(g["file_off"], 16), bytes.fromhex(g["bytes"])
        assert 0 < len(bs) <= 16 and av[off:off + len(bs)] == bs
        g_av.append((off, bs))

    g_lm = [(0, lm[:16])]
    return {
        "name": "og_highbitrate_s3_501",
        "header": "expected_mp_og_highbitrate_s3_501.h",
        "sites": sites,
        "guards": {"av-cam.bin": g_av, "libmpr.so": g_lm},
        "comment": "High-bitrate Long-GOP (200M/300M) av-cam overlay (108 sites).",
    }


def load_mp_pack_i19(av: bytes, lm: bytes, v19_site_keys: set[tuple[str, int]]) -> dict:
    si = json.loads((DESIGNS_DIR / "og_xavcsi_s3_501.json").read_text(encoding="utf8"))
    assert si["artifact_sha256"] == {"libmpr.so": hashlib.sha256(lm).hexdigest(), "av-cam.bin": hashlib.sha256(av).hexdigest()}
    sites: dict[str, list[tuple[int, bytes, bytes]]] = {"av-cam.bin": [], "libmpr.so": []}
    for p in si["patches"]:
        b = p["binary"]
        off = int(p["file_off"], 16)
        if (b, off) in v19_site_keys:
            continue
        old, new = bytes.fromhex(p["old"]), bytes.fromhex(p["new"])
        src = av if b == "av-cam.bin" else lm
        assert len(old) == len(new) <= 16 and old != new and src[off:off + len(old)] == old
        sites[b].append((off, old, new))
    assert len(sites["libmpr.so"]) + len(sites["av-cam.bin"]) == 62

    g_av: list[tuple[int, bytes]] = []
    g_lm: list[tuple[int, bytes]] = []
    seen_av: set[int] = set()
    seen_lm: set[int] = set()
    for g in si["guards"]:
        b = g["binary"]
        off, bs = int(g["file_off"], 16), bytes.fromhex(g["bytes"])
        src = av if b == "av-cam.bin" else lm
        assert 0 < len(bs) <= 16 and src[off:off + len(bs)] == bs
        if b == "av-cam.bin":
            if off not in seen_av:
                g_av.append((off, bs))
                seen_av.add(off)
        else:
            if off not in seen_lm:
                g_lm.append((off, bs))
                seen_lm.add(off)
    if 0 not in seen_lm:
        g_lm.append((0, lm[:16]))

    return {
        "name": "og_xavcsi_addon_s3_501",
        "header": "expected_mp_og_xavcsi_addon_s3_501.h",
        "sites": sites,
        "guards": {"av-cam.bin": g_av, "libmpr.so": g_lm},
        "comment": "Orthogonal XAVC S-I 4K All-Intra delta excluding V19 sites (42 sites).",
    }


def trim_cross_pack_guards(packs: list[dict]) -> list[str]:
    """Ensure no kind==0 guard in any pack overlaps any kind==1 site across all MP packs."""
    all_sites: list[tuple[str, str, int, int]] = []
    for pk in packs:
        for b in ("av-cam.bin", "libmpr.so"):
            for off, old, _ in pk["sites"][b]:
                all_sites.append((pk["name"], b, off, off + len(old)))

    notes: list[str] = []
    for pk in packs:
        for b in ("av-cam.bin", "libmpr.so"):
            kept: list[tuple[int, bytes]] = []
            for goff, gbytes in pk["guards"][b]:
                gend = goff + len(gbytes)
                hits = [
                    (sn, so, se)
                    for sn, sb, so, se in all_sites
                    if sb == b and goff < se and so < gend
                ]
                if not hits:
                    kept.append((goff, gbytes))
                    continue
                # Trim non-overlapping prefix/suffix pieces if any remain >= 4 bytes, otherwise drop.
                intervals = [(goff, gend)]
                for _, so, se in hits:
                    next_iv = []
                    for a, z in intervals:
                        if se <= a or z <= so:
                            next_iv.append((a, z))
                        else:
                            if a < so:
                                next_iv.append((a, so))
                            if se < z:
                                next_iv.append((se, z))
                    intervals = next_iv
                kept_pieces = [(a, gbytes[a - goff:z - goff]) for a, z in intervals if z - a >= 4]
                kept.extend(kept_pieces)
                notes.append(
                    f"Filtered/trimmed {pk['name']} {b} guard 0x{goff:x}+{len(gbytes)} overlapping {hits}; kept {len(kept_pieces)} slice(s)"
                )
            pk["guards"][b] = kept

    # Strict post-check assertion across all packs
    for pk in packs:
        for b in ("av-cam.bin", "libmpr.so"):
            for goff, gbytes in pk["guards"][b]:
                gend = goff + len(gbytes)
                for sn, sb, so, se in all_sites:
                    assert not (sb == b and goff < se and so < gend), (
                        f"Cross-pack guard collision: {pk['name']} {b} 0x{goff:x}..0x{gend:x} vs {sn} 0x{so:x}..0x{se:x}"
                    )
    return notes


def write_utf8_lf(path: Path, text: str) -> None:
    with open(path, "w", encoding="utf8", newline="\n") as f:
        f.write(text)


def emit_mp_pack(pk: dict, av: bytes, lm: bytes, cross_notes: list[str]) -> tuple[str, dict]:
    tabs: dict[str, list[tuple[int, int, bytes, bytes]]] = {}
    for b in ("av-cam.bin", "libmpr.so"):
        entries = [(off, 1, old, new) for off, old, new in pk["sites"][b]] + [
            (goff, 0, gbytes, b"") for goff, gbytes in pk["guards"][b]
        ]
        entries.sort(key=lambda e: (e[0], e[1]))
        for k in range(len(entries) - 1):
            a0, _, o0, _ = entries[k]
            a1, _, _, _ = entries[k + 1]
            assert a0 + len(o0) <= a1, f"{pk['name']} {b} overlap at 0x{a0:x}..0x{a0+len(o0):x} vs 0x{a1:x}"
        tabs[b] = entries

    first = tabs["av-cam.bin"][0][0] & ~0xFFF
    last = max(a + len(o) for a, _, o, _ in tabs["av-cam.bin"])
    span = ((last - first) + 0xFFF) & ~0xFFF
    assert 0x38B000 <= first and first + span <= 0x3D3000, f"{pk['name']} av-cam.bin span out of bounds"
    check_libmpr_pt_load0(lm, tabs["libmpr.so"])

    longest = max(len(tabs["av-cam.bin"]), len(tabs["libmpr.so"]))
    mp_max = max(160, (longest + 31) & ~31) if pk["name"].startswith("og_highbitrate") else ((longest + 31) & ~31)
    av_sha = hashlib.sha256(av).hexdigest()
    lm_sha = hashlib.sha256(lm).hexdigest()

    out = [
        f"/* Generated by src/a7s3_501/gen_s3_packs.py (a7S III 5.01). Do not edit. */",
        f"/* {pk['comment']} */",
        f"/* av-cam.bin {av_sha[:16]}..., libmpr.so {lm_sha[:16]}... */",
    ]
    for note in cross_notes:
        out.append(f"/* Cross-pack check: {note} */")
    out += [
        f'#define MP_DESIGN "{pk["name"]}"',
        f"#define MP_AV_FIRST 0x{first:x}UL",
        f"#define MP_AV_BYTES 0x{span:x}UL",
    ]
    if mp_max > 96:
        out.append(f"#define MP_MAX {mp_max}")
    out.append("struct mp_site { u32 off; u8 len; u8 kind; u8 stock[16]; u8 changed[16]; };")
    for b, var in (("av-cam.bin", "mp_av"), ("libmpr.so", "mp_lm")):
        out.append(f"static const struct mp_site {var}[] = {{")
        for a, kind, o, n in tabs[b]:
            out.append(f"    {{ 0x{a:x}, {len(o)}, {kind}, {{ {h16(o)} }}, {{ {h16(n)} }} }},")
        out.append("};")
    write_utf8_lf(HERE / pk["header"], "\n".join(out) + "\n")
    stats = {b: {"sites": sum(1 for e in t if e[1] == 1), "guards": sum(1 for e in t if e[1] == 0)} for b, t in tabs.items()}
    return pk["header"], stats


def emit_hdmi32_words(cp: bytes) -> tuple[str, int, int]:
    d = json.loads((DESIGNS_DIR / "hdmi32_s3_501.json").read_text(encoding="utf8"))
    assert d["artifact_sha256"]["cpapp-b.bin"] == hashlib.sha256(cp).hexdigest()

    patched = bytearray(cp)
    touched: set[int] = set()
    for p in d["patches"]:
        ram = int(p["ram_address"], 16)
        old, new = bytes.fromhex(p["old"]), bytes.fromhex(p["new"])
        assert len(old) == len(new) == p["length"] and old != new
        assert cp[ram - BASE:ram - BASE + len(old)] == old
        for idx in range(len(old)):
            assert (ram + idx) not in touched, f"Overlapping hdmi32 patch byte at 0x{ram + idx:x}"
            touched.add(ram + idx)
            patched[ram - BASE + idx] = new[idx]

    word_addrs = sorted({a & ~3 for a in touched})
    assert len(word_addrs) == 28, f"Expected 28 aligned words on s3_501, got {len(word_addrs)}"
    words: list[tuple[int, bytes, bytes]] = []
    for w in word_addrs:
        st = cp[w - BASE:w - BASE + 4]
        ch = bytes(patched[w - BASE:w - BASE + 4])
        assert st != ch
        words.append((w, st, ch))

    guards: list[tuple[int, bytes]] = []
    for g in d["guards"]:
        ga = int(g["ram_address"], 16)
        gb = bytes.fromhex(g["bytes"])
        assert 0 < len(gb) <= 16 and cp[ga - BASE:ga - BASE + len(gb)] == gb
        assert not any(ga < w + 4 and w < ga + len(gb) for w, _, _ in words), f"Guard 0x{ga:x} overlaps aligned word"
        guards.append((ga, gb))

    # Assert disjoint from lcdratio32_s3_v1 and outsz2560_s3_v1
    for other_name in ("lcdratio32_s3_v1.json", "outsz2560_s3_v1.json"):
        od = json.loads((UPSTREAM_DESIGNS_DIR / other_name).read_text(encoding="utf8"))
        for s in od["sites"]:
            oa = int(s["ram_address"], 16)
            assert not any(w < oa + 4 and oa < w + 4 for w, _, _ in words), f"Overlap with {other_name} site 0x{oa:x}"
            assert not any(ga < oa + 4 and oa < ga + len(gb) for ga, gb in guards), f"Guard overlap with {other_name} site 0x{oa:x}"

    out = [
        "/* Generated by src/a7s3_501/gen_s3_packs.py from designs/hdmi32_s3_501.json (a7S III 5.01). Do not edit. */",
        f"/* {len(words)} aligned 4-byte words, {len(guards)} guards. */",
        '#define WORDS_DESIGN "hdmi32_s3_501"',
        "struct ram_word { u32 address; u8 stock[4]; u8 changed[4]; };",
        "static const struct ram_word ram_words[] = {",
    ]
    out += [f"    {{ 0x{w:x}, {{ {hx(st)} }}, {{ {hx(ch)} }} }}," for w, st, ch in words]
    out += [
        "};",
        "struct ram_guard { u32 address; u32 len; u8 bytes[16]; };",
        "static const struct ram_guard ram_guards[] = {",
    ]
    out += [f"    {{ 0x{ga:x}, {len(gb)}, {{ {h16(gb)} }} }}," for ga, gb in guards]
    out += ["};"]
    write_utf8_lf(HERE / "expected_words_hdmi32_s3_501.h", "\n".join(out) + "\n")
    return "expected_words_hdmi32_s3_501.h", len(words), len(guards)


