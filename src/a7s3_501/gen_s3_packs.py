        (hook_off + 4, app[hook_off + 4 : hook_off + 20]),
        (int(d["calls"]["appfw_dlsym"], 16), app[int(d["calls"]["appfw_dlsym"], 16) : int(d["calls"]["appfw_dlsym"], 16) + 16]),
