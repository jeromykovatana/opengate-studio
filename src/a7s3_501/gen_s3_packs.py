#!/usr/bin/env python3
"""Generate C headers for a7S III 5.01 (a7s3_501) volatile RAM packs and s3read_v9.

Generates:
  - expected_sites_ogsq_s3_v6.h            (L5/L6: 0x8c0 + 0x820 MULTI_REC NTSC/PAL, 40 cp_sites + 2 stored records)
  - expected_mp_ogfile2560_hs_s_s3_v3.h    (V19/V20: 23.98p/25p/29.97p 149 av-cam + 12 libmpr incl. mp4_3x2 = 161 sites)
  - expected_mp_ogfile2560_hs_s_s3_nometa.h (L19/L20: 23.98p/25p/29.97p fallback 149 av-cam + 4 libmpr = 153 sites)
  - expected_words_hdmi32_s3_501.h         (H16/H17: 28 aligned 4-byte ram_word entries + 15 guards)
  - expected_mp_og_highbitrate_s3_501.h    (B19/B20: 108 av-cam sites + 54 av guards + 1 libmpr ELF magic guard)
  - expected_mp_og_xavcsi_addon_s3_501.h   (I19/I20: 62 orthogonal XAVC S-I 23.98p/25p/29.97p delta sites)
  - s3_expected.h, s3_expected.json        (s3read_v9: 25 cp_sites, 12 lm_sites, 101 av_sites)

Enforces cross-pack disjointness so no kind==0 guard in V19/L19/B19/I19 overlaps any kind==1 site across V19/L19/B19/I19.
"""
