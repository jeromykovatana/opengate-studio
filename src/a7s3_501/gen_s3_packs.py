            "",
            "/* Sensor MULTI_REC stage (ogsq_s3_v6) */",
            f"static const u32 rec_modes[N_RECS] = {{ {', '.join(f'0x{m:x}' for m in modes)} }};",
            'static const char *const rec_variant_name[REC_VARIANTS] = { "NTSC (60 Hz)", "PAL (50 Hz)" };',
