"""Generate ZV-E1 2.02 volatile RAM patch headers for Open Gate Studio.

Generates in the current source directory:
  - expected_sites_ogsq_zv_v3.h             (L5/L6: 0x8c0 + 0x820 MULTI_REC NTSC/PAL, 40 cp_sites + 2 stored records)
  - expected_mp_ogfile2560_hs_s_zv_v3.h     (V19/V20: 23.98p/25p/29.97p 149 av-cam + 12 libmpr incl. mp4_3x2 = 161 sites)
  - expected_mp_ogfile2560_hs_s_zv_nometa.h (L19/L20: 23.98p/25p/29.97p fallback 149 av-cam + 4 libmpr = 153 sites)
  - expected_words_hdmi32_zv_202.h          (H16/H17: hdmi32_zv_202 Thumb-2 -> 4-byte ram_word)
  - expected_mp_og_highbitrate_zv_202.h     (B19/B20: og_highbitrate_zv_202)
  - expected_mp_og_xavcsi_addon_zv_202.h    (I19/I20: orthogonal delta of og_xavcsi_zv_202, 32 sites)

Enforces ELF64 PT_LOAD[0] bounds, cpapp-b.bin 0x108000 RAM bounds, av-cam.bin bounds,
internal non-overlap, and CRITICAL cross-pack guard-vs-site disjointness across V19, L19, B19, I19.
"""
import argparse
import hashlib
import json
import os
import struct
from pathlib import Path

HERE = Path(__file__).resolve().parent
STUDIO_ROOT = HERE.parents[1]
WS_ROOT = STUDIO_ROOT.parent
DEFAULT_FW_DIR = Path(
    os.environ.get("SONY_FW_DIR", str(WS_ROOT / "firmwares/zve1/ghidra_targets"))
)
STUDIO_DES = Path(os.environ.get("STUDIO_DESIGNS_DIR", str(STUDIO_ROOT / "designs")))

# av-cam.bin / libmpr.so constants for ZV-E1 2.02 (from ogfile2560_hs_s_zv_v1)
AV_DESC, AV_DSIZE, AV_DTAIL, AV_NDESC, AV_UNIT, AV_CLIP = 0x38F8E8, 0x88, 8, 647, 0x38F848, 0x38D7EC
AV_PROFILES = ((0x3A50A0, 350), (0x3BAEA0, 299))
AV_PROFILE_END = 0x3BAEA0 + 299 * 0x100
LIBMPR_COMB = 0x2D32B8 - 0x205C0
CPAPP_BASE = 0x108000


def scan_rate30_longgop_zv(av: bytes, existing_av: set[int]) -> tuple[list[tuple[int, bytes, bytes]], list[tuple[int, bytes]]]:
    """Build ZV-E1 av-cam 29.97p (rate code 2) Long-GOP descriptors/profiles and key guards."""
    df = lambda off: off - AV_DTAIL if off >= 0x5C else off
    prof_off: dict[int, int] = {}
    for pbase, pcnt in AV_PROFILES:
        for i in range(pcnt):
            prof_off[struct.unpack_from("<I", av, pbase + i * 0x100 + 0x20)[0]] = pbase + i * 0x100
    fams = ((0xE, {(0, 1), (1, 1)}), (4, {(0, 0), (1, 1)}))
    new_sites: list[tuple[int, bytes, bytes]] = []
    new_guards: list[tuple[int, bytes]] = []
    seen_prof: set[int] = set()
    w, h0, h1 = 3840, 2160, 2560
    old_h, new_h = struct.pack("<H", h0), struct.pack("<H", h1)
    old_hi, new_hi = struct.pack("<I", h0), struct.pack("<I", h1)
    for codec, groups in fams:
        for k in range(AV_NDESC):
            o = AV_DESC + k * AV_DSIZE
            codecid, infr, codfr, _f0c, _cls, chroma, bitl = struct.unpack_from("<7I", av, o)
            if codecid != codec or infr != 0 or codfr != 2 or (chroma, bitl) not in groups:
                continue
            if struct.unpack_from("<HH", av, o + df(0x7E)) != (w, h0):
                continue
            key = struct.unpack_from("<I", av, o + 0x28)[0]
            assert (o + df(0x80)) not in existing_av and av[o + df(0x80) : o + df(0x80) + 2] == old_h
            new_sites.append((o + df(0x80), old_h, new_h))
            new_guards.append((o + 0x28, av[o + 0x28 : o + 0x2C]))
            if key in seen_prof:
                continue
            seen_prof.add(key)
            po = prof_off[key]
            assert struct.unpack_from("<HH", av, po + 4) == (w, h0) and struct.unpack_from("<II", av, po + 0x34) == (w, h0)
            assert struct.unpack_from("<H", av, po + 0x56)[0] == 0
            new_sites.append((po + 6, old_h, new_h))
            new_sites.append((po + 0x38, old_hi, new_hi))
            if struct.unpack_from("<HH", av, po + 0x8A) == (w, h0):
                new_sites.append((po + 0x8C, old_h, new_h))
    assert len(new_sites) == 48, f"Expected 48 rate-2 Long-GOP sites on ZV-E1, got {len(new_sites)}"
    return new_sites, new_guards


def emit_multi_rec_sites_zv(cp: bytes, design_name: str = "ogsq_zv_v3", header_name: str = "expected_sites_ogsq_zv_v3.h") -> None:
    d = json.loads(resolve_design(design_name).read_text(encoding="utf8"))
    rec_size = 0x170
    assert d["artifact_sha256"] == hashlib.sha256(cp).hexdigest() and d["record_size"] == rec_size
    sites = sorted((int(p["addr"], 16), bytes.fromhex(p["old"]), bytes.fromhex(p["new"])) for p in d["patches"])
    assert len(sites) == 40
    cp_end = CPAPP_BASE + len(cp)
    out = [
        f"/* Generated by gen_zv_studio.py from designs/{design_name}.json (ZV-E1 2.02). Do not edit. */",
        f"/* {len(sites)} sites, {sum(len(o) for _, o, _ in sites)} bytes, MULTI_REC ({', '.join(d['mode_ids'])}). */",
    ]
    rows = []
    for k, (a, old, new) in enumerate(sites):
        assert len(old) == len(new) and old != new and cp[a - CPAPP_BASE : a - CPAPP_BASE + len(old)] == old
        lo, hi = a & ~63, (a + len(old) + 63) & ~63
        assert hi - lo <= 4096 and 0x788000 <= lo and hi <= cp_end
        out.append(f"static const u8 site{k}_old[{len(old)}] = {{ {hx(old)} }};")
        out.append(f"static const u8 site{k}_new[{len(new)}] = {{ {hx(new)} }};")
        rows.append(f"    {{ 0x{a:x}, {len(old)}, site{k}_old, site{k}_new, 0, 0 }},")
    assert all(a + len(o) <= b for (a, o, _), (b, _, _) in zip(sites, sites[1:])), "sites overlap"

    modes = sorted(int(m, 16) for m in d["stored_records"])
    assert [hex(m) for m in modes] == d["mode_ids"]
    offs: list[int] | None = None
    stock_m: list[list[bytes]] = []
    new_m: list[list[bytes]] = []
    for m in modes:
        sr = d["stored_records"][hex(m)]
        o = [int(x, 16) for x in sr["offsets_that_differ"]]
        assert offs is None or o == offs
        offs = o
        st_v, nw_v = [], []
        for v in ("ntsc", "pal"):
            s, n = bytes.fromhex(sr[v]["stock"]), bytes.fromhex(sr[v]["design"])
            assert len(s) == len(n) == rec_size and s[6] == s[7] == 1 and n[6:8] == bytes((16, 19))
            assert all(s[i] == n[i] for i in range(rec_size) if i not in o)
            st_v.append(bytes(s[i] for i in o))
            nw_v.append(bytes(n[i] for i in o))
        assert len(set(st_v + nw_v)) == 4
        stock_m.append(st_v)
        new_m.append(nw_v)
    assert offs is not None and offs[:2] == [6, 7] and 2 < len(offs) <= 128
    arr = lambda tbl: "{ " + ", ".join("{ " + ", ".join(f"{{ {hx(v)} }}" for v in row) + " }" for row in tbl) + " }"
    out += [
        "#define MULTI_REC 1",
        f"#define N_RECS {len(modes)}",
        "#define REC_VARIANTS 2",
        '#define REC_VARIANTS_TEXT "NTSC 60 Hz or PAL 50 Hz"',
        f"#define REC_BYTES {len(offs)}",
        'static const u32 rec_modes[N_RECS] = { ' + ", ".join(f"0x{m:x}" for m in modes) + " };",
        'static const char *const rec_mode_text[N_RECS] = { ' + ", ".join(f'"{m:#x}"' for m in modes) + " };",
        'static const char *const rec_variant_name[REC_VARIANTS] = { "NTSC (60 Hz)", "PAL (50 Hz)" };',
        f"static const unsigned short rec_offs[REC_BYTES] = {{ {', '.join(f'0x{k:x}' for k in offs)} }};",
        f"static const u8 rec_stock[N_RECS][REC_VARIANTS][REC_BYTES] = {arr(stock_m)};",
        f"static const u8 rec_new[N_RECS][REC_VARIANTS][REC_BYTES] = {arr(new_m)};",
        f'#define SITES_TEXT "{len(sites)}"',
        f'#define ALL_TEXT "{len(sites) + len(modes)}"',
        "struct cp_site { u64 address; u32 length; const u8 *stock; const u8 *changed; const unsigned short *offs; u32 noffs; };",
        "static const struct cp_site cp_sites[] = {",
        *rows,
        "};",
    ]
    (HERE / header_name).write_text("\n".join(out) + "\n", encoding="utf8", newline="\n")
    print(f"PASS {header_name}: {len(sites)} cp_sites + {len(modes)} MULTI_REC modes ({len(offs)} offs)")


def resolve_design(name: str, prefer_vdes: bool = False) -> Path:
    del prefer_vdes
    p = STUDIO_DES / f"{name}.json"
    if p.is_file():
        return p
    raise FileNotFoundError(f"Design JSON not found for {name}: expected {p}")


def hx(b: bytes) -> str:
    return ", ".join(f"0x{x:02x}" for x in b)


def h16(b: bytes) -> str:
    return hx(b.ljust(16, b"\0"))


def first_pt_load(elf: bytes) -> tuple[int, int, int]:
    phoff = struct.unpack_from("<Q", elf, 0x20)[0]
    phentsize, phnum = struct.unpack_from("<HH", elf, 0x36)
    for k in range(phnum):
        p_type, _flags, p_off, p_vaddr, _paddr, p_filesz, p_memsz, _align = struct.unpack_from(
            "<IIQQQQQQ", elf, phoff + k * phentsize
        )
        if p_type == 1:
            assert p_off == 0 and p_vaddr == 0, "unexpected PT_LOAD[0] base"
            return p_off, p_vaddr, p_filesz
    raise RuntimeError("No PT_LOAD segment found")


def av_base_guards(av: bytes) -> list[tuple[int, bytes]]:
    g = [(AV_UNIT + 0x20, av[AV_UNIT + 0x20 : AV_UNIT + 0x30]),
         (AV_CLIP + 0x50, av[AV_CLIP + 0x50 : AV_CLIP + 0x60])]
    assert struct.unpack("<4I", g[0][1]) == (0x486, 0x474, 0x477, 0x47A)
    assert struct.unpack("<4I", g[1][1]) == (1, 3840, 2160, 23)
    return g


def build_v19(av: bytes, lm: bytes, lm_filesz: int, include_mp4: bool = True) -> dict:
    v1 = json.loads(resolve_design("ogfile2560_hs_s_zv_v1", prefer_vdes=True).read_text(encoding="utf8"))
    mp4 = json.loads(resolve_design("mp4_3x2_zv_202").read_text(encoding="utf8"))
    av_sha = hashlib.sha256(av).hexdigest()
    lm_sha = hashlib.sha256(lm).hexdigest()
    assert v1["build"] == "zve1_202" and mp4["build"] == "zve1_202"
    assert v1["artifact_sha256"] == {"libmpr.so": lm_sha, "av-cam.bin": av_sha}
    assert mp4["artifact_sha256"] == {"libmpr.so": lm_sha}

    sites_av: list[tuple[int, bytes, bytes]] = []
    sites_lm: list[tuple[int, bytes, bytes]] = []
    seen = set()

    for p in v1["patches"]:
        off, old, new = int(p["file_off"], 16), bytes.fromhex(p["old"]), bytes.fromhex(p["new"])
        src = av if p["binary"] == "av-cam.bin" else lm
        assert len(old) == len(new) <= 16 and old != new and src[off : off + len(old)] == old
        key = (p["binary"], off)
        assert key not in seen
        seen.add(key)
        (sites_av if p["binary"] == "av-cam.bin" else sites_lm).append((off, old, new))

    existing_av = {off for off, _, _ in sites_av}
    r30_sites, r30_guards = scan_rate30_longgop_zv(av, existing_av)
    sites_av.extend(r30_sites)

    if include_mp4:
        for p in mp4["patches"]:
            assert p["binary"] == "libmpr.so"
            off, old, new = int(p["file_off"], 16), bytes.fromhex(p["old"]), bytes.fromhex(p["new"])
            assert len(old) == len(new) <= 16 and old != new and lm[off : off + len(old)] == old
            assert off + len(old) <= lm_filesz
            key = ("libmpr.so", off)
            assert key not in seen
            seen.add(key)
            sites_lm.append((off, old, new))
        assert len(sites_lm) == 12
    else:
        assert len(sites_lm) == 4

    assert len(sites_av) == 149

    guards_av = av_base_guards(av)
    for x in v1["descriptors"]:
        o = AV_DESC + x["descriptor"] * AV_DSIZE + 0x28
        assert struct.unpack_from("<I", av, o)[0] == x["profile_key"]
        guards_av.append((o, av[o : o + 4]))
    guards_av.extend(r30_guards)

    guards_lm: list[tuple[int, bytes]] = []
    if include_mp4:
        for g in mp4["guards"]:
            off = int(g["file_off"], 16)
            b = bytes.fromhex(g["bytes"])
            assert lm[off : off + len(b)] == b and off + len(b) <= lm_filesz
            guards_lm.append((off, b))
    else:
        guards_lm.append((0, lm[:16]))
    for p in v1["patches"]:
        if p["binary"] == "libmpr.so":
            off = int(p["file_off"], 16)
            assert (off - 6 - LIBMPR_COMB) % 0x18 == 0
            assert struct.unpack_from("<H", lm, off - 2)[0] == 3840
            guards_lm.append((off - 6, lm[off - 6 : off]))

    return {
        "name": "ogfile2560_hs_s_zv_v3" if include_mp4 else "ogfile2560_hs_s_zv_nometa",
        "header": "expected_mp_ogfile2560_hs_s_zv_v3.h" if include_mp4 else "expected_mp_ogfile2560_hs_s_zv_nometa.h",
        "av_sites": sites_av,
        "lm_sites": sites_lm,
        "av_guards": guards_av,
        "lm_guards": guards_lm,
        "av_sha": av_sha,
        "lm_sha": lm_sha,
        "lm_filesz": lm_filesz,
        "av_page_bounds": (AV_CLIP & ~0xFFF, (AV_PROFILE_END + 0xFFF) & ~0xFFF),
    }


def build_b19(av: bytes, lm: bytes, lm_filesz: int) -> dict:
    hb = json.loads(resolve_design("og_highbitrate_zv_202").read_text(encoding="utf8"))
    av_sha = hashlib.sha256(av).hexdigest()
    assert hb["build"] == "zve1_202" and hb["persistent_writes"] is False
    assert hb["artifact_sha256"]["av-cam.bin"] == av_sha

    sites_av: list[tuple[int, bytes, bytes]] = []
    for p in hb["patches"]:
        assert p["binary"] == "av-cam.bin"
        off, old, new = int(p["file_off"], 16), bytes.fromhex(p["old"]), bytes.fromhex(p["new"])
        assert len(old) == len(new) <= 16 and old != new and av[off : off + len(old)] == old
        sites_av.append((off, old, new))

    guards_av: list[tuple[int, bytes]] = []
    for g in hb["guards"]:
        assert g["binary"] == "av-cam.bin"
        off, b = int(g["file_off"], 16), bytes.fromhex(g["bytes"])
        assert 0 < len(b) <= 16 and av[off : off + len(b)] == b
        guards_av.append((off, b))

    guards_lm = [(0, lm[:16])]
    assert len(sites_av) == 108 and len(guards_av) == 54
    return {
        "name": "og_highbitrate_zv_202",
        "header": "expected_mp_og_highbitrate_zv_202.h",
        "av_sites": sites_av,
        "lm_sites": [],
        "av_guards": guards_av,
        "lm_guards": guards_lm,
        "av_sha": av_sha,
        "lm_sha": hashlib.sha256(lm).hexdigest(),
        "lm_filesz": lm_filesz,
        "av_page_bounds": None,
    }


def build_i19(av: bytes, lm: bytes, lm_filesz: int, v19_keys: set[tuple[str, int]]) -> dict:
    xsi = json.loads(resolve_design("og_xavcsi_zv_202").read_text(encoding="utf8"))
    av_sha = hashlib.sha256(av).hexdigest()
    lm_sha = hashlib.sha256(lm).hexdigest()
    assert xsi["build"] == "zve1_202" and xsi["persistent_writes"] is False
    assert xsi["artifact_sha256"] == {"libmpr.so": lm_sha, "av-cam.bin": av_sha}

    sites_av: list[tuple[int, bytes, bytes]] = []
    sites_lm: list[tuple[int, bytes, bytes]] = []
    for p in xsi["patches"]:
        off = int(p["file_off"], 16)
        if (p["binary"], off) in v19_keys:
            continue
        old, new = bytes.fromhex(p["old"]), bytes.fromhex(p["new"])
        src = av if p["binary"] == "av-cam.bin" else lm
        assert len(old) == len(new) <= 16 and old != new and src[off : off + len(old)] == old
        if p["binary"] == "libmpr.so":
            assert off + len(old) <= lm_filesz
            sites_lm.append((off, old, new))
        else:
            sites_av.append((off, old, new))

    assert len(sites_av) == 30 and len(sites_lm) == 2

    guards_av: list[tuple[int, bytes]] = []
    guards_lm: list[tuple[int, bytes]] = []
    for g in xsi["guards"]:
        off, b = int(g["file_off"], 16), bytes.fromhex(g["bytes"])
        src = av if g["binary"] == "av-cam.bin" else lm
        assert 0 < len(b) <= 16 and src[off : off + len(b)] == b
        if g["binary"] == "libmpr.so":
            assert off + len(b) <= lm_filesz
            guards_lm.append((off, b))
        else:
            guards_av.append((off, b))

    return {
        "name": "og_xavcsi_addon_zv_202",
        "header": "expected_mp_og_xavcsi_addon_zv_202.h",
        "av_sites": sites_av,
        "lm_sites": sites_lm,
        "av_guards": guards_av,
        "lm_guards": guards_lm,
        "av_sha": av_sha,
        "lm_sha": lm_sha,
        "lm_filesz": lm_filesz,
        "av_page_bounds": None,
    }


def check_and_emit_mp_packs(packs: list[dict]) -> None:
    # Global cross-pack site-vs-site and guard-vs-site disjointness check
    all_sites: list[tuple[str, str, int, int]] = []
    for pk in packs:
        for bname, key in (("av-cam.bin", "av_sites"), ("libmpr.so", "lm_sites")):
            for off, old, _ in pk[key]:
                all_sites.append((pk["name"], bname, off, off + len(old)))

    # Assert no site overlaps any site of another pack (except intentional V19 vs L19 fallback pair)
    for i in range(len(all_sites)):
        n1, b1, s1, e1 = all_sites[i]
        for j in range(i + 1, len(all_sites)):
            n2, b2, s2, e2 = all_sites[j]
            if {n1, n2} == {"ogfile2560_hs_s_zv_v3", "ogfile2560_hs_s_zv_nometa"}:
                continue
            if b1 == b2 and s1 < e2 and s2 < e1:
                raise AssertionError(
                    f"Site overlap between {n1} {b1} {s1:#x}..{e1:#x} and {n2} {s2:#x}..{e2:#x}"
                )

    for pk in packs:
        filtered_notes = []
        for bname, gkey in (("av-cam.bin", "av_guards"), ("libmpr.so", "lm_guards")):
            kept = []
            for goff, gb in pk[gkey]:
                gend = goff + len(gb)
                coll = [
                    (sn, sb, ss, se)
                    for sn, sb, ss, se in all_sites
                    if sb == bname and goff < se and ss < gend
                ]
                if coll:
                    raise AssertionError(
                        f"Cross-pack guard collision in {pk['name']} {bname} {goff:#x}..{gend:#x} vs {coll}"
                    )
                kept.append((goff, gb))
            pk[gkey] = kept

        tabs = {}
        for bname, skey, gkey in (
            ("av-cam.bin", "av_sites", "av_guards"),
            ("libmpr.so", "lm_sites", "lm_guards"),
        ):
            entries = [(o, 1, old, new) for o, old, new in pk[skey]] + [
                (o, 0, b, b"") for o, b in pk[gkey]
            ]
            entries.sort(key=lambda r: (r[0], r[1]))
            for k in range(len(entries) - 1):
                a_end = entries[k][0] + len(entries[k][2])
                b_start = entries[k + 1][0]
                assert a_end <= b_start, (
                    f"Overlapping entries in {pk['name']} {bname}: {entries[k][0]:#x}..{a_end:#x} vs {b_start:#x}"
                )
            tabs[bname] = entries

        av_tab = tabs["av-cam.bin"]
        lm_tab = tabs["libmpr.so"]
        first = av_tab[0][0] & ~0xFFF
        last = max(o + len(old) for o, _, old, _ in av_tab)
        span = ((last - first) + 0xFFF) & ~0xFFF
        if pk["av_page_bounds"] is not None:
            lo_b, hi_b = pk["av_page_bounds"]
            assert lo_b <= first and first + span <= hi_b
        assert max(o + len(old) for o, _, old, _ in lm_tab) <= pk["lm_filesz"]

        longest = max(len(av_tab), len(lm_tab))
        mp_max = max(96, (longest + 31) & ~31)
        out = [
            f"/* Generated by gen_zv_studio.py for {pk['name']} (ZV-E1 2.02). Do not edit. */",
            f"/* av-cam.bin {pk['av_sha'][:16]}..., libmpr.so {pk['lm_sha'][:16]}... */",
            f"/* Cross-pack disjointness verified against V19/B19/I19: 0 guard-vs-site collisions. {'; '.join(filtered_notes)} */",
            f'#define MP_DESIGN "{pk["name"]}"',
            f"#define MP_AV_FIRST 0x{first:x}UL                 /* file offset of the first page read of av-cam.bin */",
            f"#define MP_AV_BYTES 0x{span:x}UL                  /* whole pages: every entry of mp_av lies inside */",
            f"#define MP_MAX {mp_max}                          /* room for {longest} entries (levels 19 and 20) */",
            "struct mp_site { u32 off; u8 len; u8 kind; u8 stock[16]; u8 changed[16]; };",
        ]
        for bname, var in (("av-cam.bin", "mp_av"), ("libmpr.so", "mp_lm")):
            out.append(f"static const struct mp_site {var}[] = {{      /* {bname}: file offsets */")
            out += [
                f"    {{ 0x{o:x}, {len(old)}, {kind}, {{ {h16(old)} }}, {{ {h16(new)} }} }},"
                for o, kind, old, new in tabs[bname]
            ]
            out.append("};")
        (HERE / pk["header"]).write_text("\n".join(out) + "\n", encoding="utf8", newline="\n")
        print(
            f"PASS {pk['header']}: av={len(pk['av_sites'])}s/{len(pk['av_guards'])}g, "
            f"lm={len(pk['lm_sites'])}s/{len(pk['lm_guards'])}g, MP_MAX={mp_max}"
        )


def build_h16(cp: bytes) -> None:
    hd = json.loads(resolve_design("hdmi32_zv_202").read_text(encoding="utf8"))
    cp_sha = hashlib.sha256(cp).hexdigest()
    assert hd["build"] == "zve1_202" and hd["persistent_writes"] is False
